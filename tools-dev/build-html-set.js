#!/usr/bin/env node
/* tools-dev/build-html-set.js
   Builds html-edition/: the ENTIRE demo as a SET of .html files, every one
   under the firewall's ~1 MB ceiling, that runs multi-file exactly like
   workspace/demo/ runs with .js files.

   Why .html works: Edge/Chromium executes a <script src> target by content,
   not extension, over file:// (no server, no MIME headers, no nosniff). So
   each kernel/module/data file ships as pure JS named .html - it crosses
   the firewall as an HTML file, lands in the folder structure unchanged,
   and IS the runtime file. No conversion, no renaming, no unpacker.
   Updating the app inside = replace one .html, refresh.

   Oversized data files (over the per-file budget) are split into
   -part1..N.html files: part 1 initializes the entity with its version and
   an empty rows array, every part appends its slice with concat, and
   index.html lists the parts in order. Everything else copies VERBATIM,
   only the extension changes.

   Run from anywhere:  node tools-dev/build-html-set.js
   Regenerate after every release. Never edit html-edition/ by hand. */

"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const crypto = require("crypto");

const ROOT = path.resolve(__dirname, "..");
const DEMO = path.join(ROOT, "workspace", "demo");
const OUT = path.join(ROOT, "html-edition");

/* Per-file content budget. 650 KB stays under 1 MB even if an email
   gateway measures the base64-encoded attachment (x1.37). */
const BUDGET = 650 * 1024;
const HARD_CAP = 1000 * 1000;

function fail(msg) { console.error("BUILD FAILED: " + msg); process.exit(1); }
const sha12 = buf => crypto.createHash("sha256").update(buf).digest("hex").slice(0, 12);
const kb = n => (n / 1024).toFixed(1) + " KB";

const srcIndex = path.join(DEMO, "index.html");
if (!fs.existsSync(srcIndex)) fail("missing " + srcIndex);
const html = fs.readFileSync(srcIndex, "utf8");

/* Release stamp from the data, not the wall clock - rebuilds of an
   unchanged demo/ are byte-identical. */
let relNumber = "R?", relDate = "";
try {
  const m = fs.readFileSync(path.join(DEMO, "data", "release.js"), "utf8")
    .match(/number\s*:\s*"([^"]+)"[\s\S]*?date\s*:\s*"([^"]+)"/);
  if (m) { relNumber = m[1]; relDate = m[2]; }
} catch (e) { /* stamp stays R? */ }
const STAMP = relNumber + (relDate ? " " + relDate : "");

/* Fresh output tree every build so retired part files never linger. */
fs.rmSync(OUT, { recursive: true, force: true });
["", "kernel", "modules", "data"].forEach(d => fs.mkdirSync(path.join(OUT, d), { recursive: true }));

const manifest = []; // {rel, bytes, sha, note}
function emit(rel, content, note) {
  const buf = Buffer.from(content, "utf8");
  if (buf.length > HARD_CAP) fail(rel + " is " + kb(buf.length) + " - over the 1 MB hard cap");
  fs.writeFileSync(path.join(OUT, rel), buf);
  manifest.push({ rel: rel, bytes: buf.length, sha: sha12(buf), note: note || "" });
}

/* Split one data file into order-listed parts. Executes the file to get the
   entity object, then re-serializes rows in slices - values and key order
   survive exactly (the sources are JSON literals already). */
function splitDataFile(rel, js) {
  const sandbox = { window: {} };
  vm.runInNewContext(js, sandbox, { filename: rel });
  const keys = Object.keys(sandbox.window.GRC_DATA || {});
  if (keys.length !== 1) fail(rel + " defines " + keys.length + " GRC_DATA entries - expected exactly 1");
  const key = keys[0];
  const obj = sandbox.window.GRC_DATA[key];
  if (!Array.isArray(obj.rows) || obj.rows.length < 2) fail(rel + " is oversized but has no rows array to split on");

  const rows = obj.rows.map(r => JSON.stringify(r));
  const chunks = [];
  let cur = [], curLen = 0;
  rows.forEach(r => {
    if (curLen && curLen + r.length + 2 > BUDGET - 1600) { chunks.push(cur); cur = []; curLen = 0; }
    cur.push(r); curLen += r.length + 2;
  });
  if (cur.length) chunks.push(cur);

  const ref = 'window.GRC_DATA[' + JSON.stringify(key) + ']';
  const base = rel.replace(/\.js$/, "");
  const parts = [];
  chunks.forEach((chunk, i) => {
    const partRel = base + "-part" + (i + 1) + ".html";
    let out = "/* " + partRel + " - part " + (i + 1) + " of " + chunks.length +
      " of " + rel + " (" + STAMP + "). Pure JS named .html for firewall transfer;\n" +
      "   loaded by index.html via <script src>. Parts must all be present and are\n" +
      "   listed in index.html in order. Generated by tools-dev/build-html-set.js. */\n";
    if (i === 0) {
      out += "window.GRC_DATA = window.GRC_DATA || {};\n" +
        ref + " = " + JSON.stringify(Object.assign({}, obj, { rows: [] })) + ";\n";
    }
    out += ref + ".rows = " + ref + ".rows.concat([\n" + chunk.join(",\n") + "\n]);\n";
    emit(partRel, out, "part " + (i + 1) + "/" + chunks.length + " of " + rel);
    parts.push(partRel);
  });
  return parts;
}

/* Walk index.html's script tags: carry each referenced file over as .html
   (verbatim when it fits, split when it does not) and rewrite the tag(s). */
let tagsIn = 0, tagsOut = 0;
let out = html.replace(/^([ \t]*)<script src="([^"]+)"><\/script>[ \t]*$/gm,
  function (whole, indent, rel) {
    tagsIn++;
    const file = path.join(DEMO, rel);
    if (!fs.existsSync(file)) fail("index.html references missing file: " + rel);
    const js = fs.readFileSync(file, "utf8");
    let outRels;
    if (Buffer.byteLength(js) > BUDGET && rel.indexOf("data/") === 0) {
      outRels = splitDataFile(rel, js);
    } else if (Buffer.byteLength(js) > BUDGET) {
      fail(rel + " is over budget and not a data file - split it at the source first");
    } else {
      const outRel = rel.replace(/\.js$/, ".html");
      emit(outRel, js, "verbatim copy of " + rel);
      outRels = [outRel];
    }
    tagsOut += outRels.length;
    return outRels.map(r => indent + '<script src="' + r + '"></script>').join("\n");
  });

if (tagsIn === 0) fail("no <script src> tags found in index.html");
if (/<script src="[^"]*\.js"/.test(out)) fail("a .js script reference survived - pattern drift in index.html");

/* Head: build stamp, plus the relocation affordance - uncomment <base> to
   run index.html from outside the folder that holds the structure. */
out = out.replace(/(<!-- GRC index\.html[^>]*-->)/,
  "$1\n<!-- HTML EDITION " + STAMP + " - the multi-file demo with every file named\n" +
  "     .html so each one crosses the firewall alone, under 1 MB. Generated by\n" +
  "     tools-dev/build-html-set.js from workspace/demo/; see READ-ME-FIRST.html.\n" +
  "     Self-contained: no network access needed or attempted. -->");
out = out.replace(/(<title>[^<]*<\/title>)/,
  "$1\n<!-- To run this index.html from OUTSIDE the folder that holds kernel\\\n" +
  "     modules\\ data\\ : uncomment the next line and point it at that folder.\n" +
  '<base href="file:///C:/GRC/demo-html/">\n' +
  "-->");
out = out.replace(/<!-- Kernel first[\s\S]*?-->/,
  "<!-- Load order: kernel, then data (large entities as -part1..N, in order),\n" +
  "     then modules. To update the app: replace ONE file below and refresh\n" +
  "     (Ctrl+F5). A data file rebuilt as a single local .html can replace all\n" +
  "     of its part lines with one line - files created on this machine have\n" +
  "     no transfer limit. -->");

emit("index.html", out, "shell - rewritten script list");

/* READ-ME-FIRST.html: instructions + packing list. It crosses too. */
const groups = { "": "(root)", kernel: "kernel\\", modules: "modules\\", data: "data\\" };
const rows = manifest.map(function (f, i) {
  const dir = f.rel.indexOf("/") < 0 ? "(root)" : groups[f.rel.split("/")[0]];
  return "<tr><td>" + (i + 1) + "</td><td class=m>" + f.rel.split("/").pop() +
    "</td><td>" + dir + "</td><td class=n>" + kb(f.bytes) + "</td><td class=m>" +
    f.sha + "</td><td>" + f.note + "</td></tr>";
}).join("\n");
const totalBytes = manifest.reduce((a, f) => a + f.bytes, 0);
const readme = '<!DOCTYPE html>\n<!-- READ-ME-FIRST.html (' + STAMP + ') - generated by tools-dev/build-html-set.js -->\n' +
  '<html lang="en"><head><meta charset="utf-8"><title>Meridian GRC - HTML edition ' + relNumber + '</title>\n' +
  '<style>body{font:14px/1.5 "Segoe UI",system-ui,sans-serif;color:#1f2430;max-width:940px;margin:24px auto;padding:0 16px}\n' +
  'h1{font-size:20px}h2{font-size:15px;margin-top:22px}code,.m{font-family:Consolas,Menlo,monospace;font-size:12.5px}\n' +
  'table{border-collapse:collapse;width:100%;font-size:12.5px}th,td{border:1px solid #d9dde3;padding:3px 8px;text-align:left}\n' +
  'th{background:#f2f4f6;font-size:11px;text-transform:uppercase;letter-spacing:.4px}.n{text-align:right;white-space:nowrap}\n' +
  'li{margin:4px 0}.note{background:#fdf9f0;border:1px solid #ecdfc3;border-radius:6px;padding:8px 12px}</style></head><body>\n' +
  '<h1>Meridian GRC mockup - HTML edition (' + STAMP + ')</h1>\n' +
  '<p>The full demo as <b>' + manifest.length + ' files, every one an .html under 1&nbsp;MB</b>, so each\n' +
  'file crosses the firewall on its own. The files run exactly as they are - no renaming, no\n' +
  'conversion, no unpacking tool. All but index.html are the app\u2019s JS carried with an .html\n' +
  'name; Edge runs a <code>&lt;script src&gt;</code> target by its content, not its extension.</p>\n' +
  '<h2>Set up once</h2>\n<ol>\n' +
  '<li>Make a folder, e.g. <code>C:\\GRC\\demo-html\\</code> (Documents works if C:\\ is locked down),\n' +
  'with three subfolders: <code>kernel</code>, <code>modules</code>, <code>data</code>.</li>\n' +
  '<li>Place every file per the packing list below. <code>index.html</code> and this file sit at the root.</li>\n' +
  '<li>Double-click <code>index.html</code>. Click <b>Preflight</b> in the banner: it must say\n' +
  '<b>NO TRAPPED ERRORS</b> with every entity loaded (850 RAUs, 8,000 MCRs, 5,146 controls\u2026).</li>\n' +
  '</ol>\n' +
  '<p class=note>If Edge refuses to open a file that came from outside, clear the download mark first:\n' +
  'right-click the file &rarr; Properties &rarr; tick <b>Unblock</b> &rarr; OK. Files you create locally never have it.</p>\n' +
  '<h2>Updating one file at a time</h2>\n<ul>\n' +
  '<li>Replace the one changed .html in its folder, then hard-refresh the open demo (Ctrl+F5). That is the whole update.</li>\n' +
  '<li>The kit and runbook name files the canonical way - <code>modules/rcsa.js</code> here is\n' +
  '<code>modules\\rcsa.html</code>. Same content, same Copilot workflow; just save with the .html name.</li>\n' +
  '<li>A brand-new module still needs its one <code>&lt;script&gt;</code> line added in index.html, same as the .js edition.</li>\n' +
  '<li>Large data entities ship split as <code>-part1..N</code>; every part must be present, in the order\n' +
  'index.html lists. Data you rebuild locally (e.g. from DataForge) has no transfer limit - one\n' +
  'whole-entity file saved as .html can replace all its part lines with a single line.</li>\n' +
  '<li>index.html normally sits at the structure root. To run it from somewhere else, open it in\n' +
  'Notepad and follow the <code>&lt;base href&gt;</code> comment near the top: point it at the folder that\n' +
  'holds <code>kernel\\ modules\\ data\\</code>.</li>\n' +
  '</ul>\n' +
  '<h2>Packing list - ' + manifest.length + ' files, ' + kb(totalBytes) + ' total</h2>\n' +
  '<p>Check arrivals against the size column (sha256 prefix for a byte-exact check if you have a tool for it).</p>\n' +
  '<table>\n<tr><th>#</th><th>file</th><th>folder</th><th>size</th><th>sha256 (12)</th><th>what it is</th></tr>\n' +
  rows + '\n</table>\n' +
  '<p>Generated from <code>workspace/demo/</code> at release ' + STAMP + ' by\n' +
  '<code>node tools-dev/build-html-set.js</code>. Regenerated whole every release - never edited by hand.</p>\n' +
  '</body></html>\n';
fs.writeFileSync(path.join(OUT, "READ-ME-FIRST.html"), readme);

/* Report */
console.log("html-edition/ built (" + STAMP + "): " + (manifest.length + 1) + " files, " +
  tagsIn + " script tags -> " + tagsOut);
const biggest = manifest.slice().sort((a, b) => b.bytes - a.bytes)[0];
console.log("largest file: " + biggest.rel + "  " + kb(biggest.bytes));
const parts = manifest.filter(f => /-part\d+\.html$/.test(f.rel));
const partEntities = {};
parts.forEach(f => { const e = f.rel.replace(/-part\d+\.html$/, ""); partEntities[e] = (partEntities[e] || 0) + 1; });
Object.keys(partEntities).forEach(e => console.log("split: " + e + ".js -> " + partEntities[e] + " parts"));
console.log("total payload: " + kb(totalBytes) + " + READ-ME-FIRST.html (" + kb(Buffer.byteLength(readme)) + ")");
