#!/usr/bin/env node
/* tools-dev/build-single-html.js
   Builds the single-file firewall-crossing artifact: reads
   workspace/demo/index.html, replaces every <script src="..."> with the
   file's contents inlined, and writes ONE self-contained HTML at the repo
   root. Same method as the risk-instance-viewer: one .html, zero external
   references, crosses the firewall as a plain HTML file and runs by
   double-click.

   Run from anywhere:  node tools-dev/build-single-html.js
   Regenerate after every release (the output embeds whatever demo/ holds).

   The multi-file workspace/demo/ tree stays the editing + real-data
   structure; this output is the delivery vehicle only. Never edit the
   output by hand. */

"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const DEMO = path.join(ROOT, "workspace", "demo");
const SRC = path.join(DEMO, "index.html");
const OUT = path.join(ROOT, "meridian-grc-mockup.html");

function fail(msg) { console.error("BUILD FAILED: " + msg); process.exit(1); }

if (!fs.existsSync(SRC)) fail("missing " + SRC);
const html = fs.readFileSync(SRC, "utf8");

/* Release stamp comes from the data, not the wall clock, so rebuilding an
   unchanged demo/ yields a byte-identical file (clean git diffs). */
let relNumber = "R?", relDate = "";
try {
  const relSrc = fs.readFileSync(path.join(DEMO, "data", "release.js"), "utf8");
  const m = relSrc.match(/number\s*:\s*"([^"]+)"[\s\S]*?date\s*:\s*"([^"]+)"/);
  if (m) { relNumber = m[1]; relDate = m[2]; }
} catch (e) { /* stamp stays R? */ }

/* Inside an inline <script>, the HTML parser ends the element at the first
   "</script" and enters a comment-escaped state at "<!--". Neither sequence
   exists in any demo file today (verified), but escape defensively so a
   future data string cannot corrupt the build. Both rewrites are inert
   inside JS strings, regexes, and comments. */
function escapeForInline(js) {
  return js.replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--");
}

const inlined = [];
let bytesIn = 0;

let out = html.replace(/^([ \t]*)<script src="([^"]+)"><\/script>[ \t]*$/gm,
  function (whole, indent, rel) {
    const file = path.join(DEMO, rel);
    if (!fs.existsSync(file)) fail("index.html references missing file: " + rel);
    const js = fs.readFileSync(file, "utf8");
    bytesIn += Buffer.byteLength(js);
    inlined.push({ rel: rel, bytes: Buffer.byteLength(js) });
    return indent + '<script>\n/* ==INLINE:' + rel + '== */\n' +
      escapeForInline(js).replace(/\s*$/, "") + "\n" + indent + "</script>";
  });

if (/<script src=/.test(out)) fail("a <script src> tag survived inlining - pattern drift in index.html");
if (inlined.length === 0) fail("no <script src> tags found in index.html");

/* Swap the multi-file assembly comment for a single-file note; tolerate the
   comment changing shape in a future release. */
out = out.replace(/<!-- Kernel first[\s\S]*?-->/,
  "<!-- SINGLE-FILE BUILD: kernel, data, and modules are inlined below in\n" +
  "     load order. To change code or swap in real data, use the multi-file\n" +
  "     workspace (demo/) and rebuild; do not edit this file by hand. -->");

/* Build stamp directly under the version comment at the top. */
out = out.replace(/(<!-- GRC index\.html[^>]*-->)/,
  "$1\n<!-- SINGLE-FILE ARTIFACT " + relNumber + (relDate ? " " + relDate : "") +
  " - generated by tools-dev/build-single-html.js from workspace/demo/ (" +
  inlined.length + " files inlined). Self-contained: no network access needed or attempted. -->");

fs.writeFileSync(OUT, out);

const kb = n => (n / 1024).toFixed(1) + " KB";
const groups = {};
inlined.forEach(f => {
  const g = f.rel.split("/")[0];
  groups[g] = (groups[g] || 0) + f.bytes;
});
console.log("Inlined " + inlined.length + " files from workspace/demo/ (" + relNumber + ")");
Object.keys(groups).forEach(g => console.log("  " + g.padEnd(8) + kb(groups[g])));
const total = fs.statSync(OUT).size;
console.log("Output: " + path.relative(ROOT, OUT) + "  " + kb(total));
if (total > 25 * 1024 * 1024) {
  console.warn("WARNING: output exceeds 25 MB - common email gateways will refuse it.");
}
